'use strict';
const {spawnSync}=require('node:child_process');
const path=require('node:path');
const fs=require('node:fs');
const root=path.resolve(__dirname,'..');
const python=path.join(root,'.desktop-venv/bin/python');
if(!fs.existsSync(python))throw new Error('Create .desktop-venv with Python 3.9–3.12 and install pyinstaller==6.20.0. See desktop/README.md.');
const phoneDeps=spawnSync(python,['-c','import aiortc, av, pylibsrtp, cryptography'],{cwd:root,stdio:'inherit'});
if(phoneDeps.status!==0)throw new Error('Install desktop/phone-requirements.txt into .desktop-venv before packaging phone import.');
const result=spawnSync(python,['-m','PyInstaller','--noconfirm','--onedir','--name','pixfun-service','--distpath','build-desktop/backend','--workpath','build-desktop/work','--specpath','build-desktop','--target-arch','arm64','--add-data',`${path.join(root,'creator-skills')}:creator-skills`,'--add-data',`${path.join(root,'phone-web')}:phone-web`,'desktop_service.py'],{cwd:root,stdio:'inherit',env:{...process.env,PYINSTALLER_CONFIG_DIR:path.join(root,'build-desktop/pyinstaller-cache')}});
if(result.status!==0)process.exit(result.status??1);
if(!process.argv.includes('--skip-icon'))require('./build-desktop-icon.cjs');
